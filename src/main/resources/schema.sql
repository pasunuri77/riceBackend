-- Create Returns and Refunds tables
CREATE TABLE IF NOT EXISTS return_requests (
    id bigint generated by default as identity primary key,
    return_number varchar(255) not null unique,
    order_id bigint not null,
    customer_id bigint not null,
    status varchar(50) not null,
    reason varchar(255) not null,
    customer_details text,
    refund_method varchar(50) not null,
    refund_amount numeric(38,2) not null default 0,
    admin_reason varchar(255),
    admin_note text,
    return_instructions text,
    submitted_at timestamp(6) not null default current_timestamp,
    reviewed_at timestamp(6),
    approved_at timestamp(6),
    rejected_at timestamp(6),
    refund_processed_at timestamp(6),
    created_at timestamp(6) not null default current_timestamp,
    updated_at timestamp(6),
    CONSTRAINT fk_return_order FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT fk_return_customer FOREIGN KEY (customer_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS return_request_items (
    id bigint generated by default as identity primary key,
    return_request_id bigint not null,
    order_item_id bigint not null,
    product_id varchar(255),
    product_name varchar(255) not null,
    variant_name varchar(255),
    unit_price numeric(38,2) not null,
    requested_quantity integer not null,
    approved_quantity integer,
    refund_amount numeric(38,2) not null,
    CONSTRAINT fk_return_item_req FOREIGN KEY (return_request_id) REFERENCES return_requests(id) ON DELETE CASCADE,
    CONSTRAINT fk_return_item_order_item FOREIGN KEY (order_item_id) REFERENCES order_items(id),
    CONSTRAINT fk_return_item_product FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE IF NOT EXISTS refunds (
    id bigint generated by default as identity primary key,
    return_request_id bigint not null,
    order_id bigint not null,
    payment_method varchar(50) not null,
    payment_reference varchar(255),
    amount numeric(38,2) not null,
    status varchar(50) not null,
    created_at timestamp(6) not null default current_timestamp,
    processed_at timestamp(6),
    CONSTRAINT fk_refund_return FOREIGN KEY (return_request_id) REFERENCES return_requests(id),
    CONSTRAINT fk_refund_order FOREIGN KEY (order_id) REFERENCES orders(id)
);

CREATE INDEX IF NOT EXISTS idx_return_requests_order_id ON return_requests(order_id);
CREATE INDEX IF NOT EXISTS idx_return_requests_customer_id ON return_requests(customer_id);
CREATE INDEX IF NOT EXISTS idx_return_requests_status ON return_requests(status);
CREATE INDEX IF NOT EXISTS idx_return_request_items_req_id ON return_request_items(return_request_id);
CREATE INDEX IF NOT EXISTS idx_refunds_return_req_id ON refunds(return_request_id);

